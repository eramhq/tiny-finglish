/**
 * Normalization is the foundation every downstream metric rests on, so it gets
 * the strictest tests in the repo: a property test for idempotence over the
 * full variant table, and a cross-language fixture that fails if the
 * TypeScript and Python implementations ever diverge.
 */
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { foldForMatch, isNormalized, normalize } from "../src/normalize.ts";
import { ZWNJ } from "../src/unicode.ts";

const root = new URL("..", import.meta.url);

interface NormalizationCase {
  group: string;
  input: string;
  output: string;
  fold: string;
}

const cases: NormalizationCase[] = readFileSync(
  new URL("data/fixtures/normalization.jsonl", root), "utf8",
).split("\n").filter(Boolean).map((l) => JSON.parse(l) as NormalizationCase);

const inputs: string[] = Object.values(
  JSON.parse(readFileSync(new URL("data/fixtures/normalization-inputs.json", root), "utf8")).groups,
).flat() as string[];

describe("normalize", () => {
  it("has fixtures to run", () => {
    expect(cases.length).toBeGreaterThan(40);
  });

  it("matches the committed fixture for every case", () => {
    for (const testCase of cases) {
      expect(normalize(testCase.input), `case ${testCase.group}`).toBe(testCase.output);
    }
  });

  // These fixtures were generated by the Python implementation, so agreement
  // here is the cross-language parity check for the normalizer.
  it("agrees with the Python implementation on foldForMatch", () => {
    for (const testCase of cases) {
      expect(foldForMatch(testCase.input), `case ${testCase.group}`).toBe(testCase.fold);
    }
  });

  // The property the plan singles out.
  it("is idempotent across every variant", () => {
    for (const input of inputs) {
      const once = normalize(input);
      expect(normalize(once), `not idempotent for ${JSON.stringify(input)}`).toBe(once);
      expect(isNormalized(once)).toBe(true);
    }
  });

  it("is idempotent for every code point in the Arabic blocks", () => {
    for (let cp = 0x0600; cp <= 0x06ff; cp++) {
      const probe = `ا${String.fromCodePoint(cp)}ب`;
      const once = normalize(probe);
      expect(normalize(once), `not idempotent at U+${cp.toString(16)}`).toBe(once);
    }
    for (let cp = 0xfb50; cp <= 0xfdff; cp += 7) {
      const once = normalize(String.fromCodePoint(cp));
      expect(normalize(once)).toBe(once);
    }
  });

  it("folds Arabic letters to their Persian counterparts", () => {
    expect(normalize("كتاب")).toBe("کتاب");
    expect(normalize("يك")).toBe("یک");
  });

  it("normalizes all three encodings of ۀ to ه + hamza, the only NFC-stable one", () => {
    const canonical = "هٔ";
    expect(normalize("ۀ")).toBe(canonical);
    expect(normalize("ۀ")).toBe(canonical);
    expect(normalize(canonical)).toBe(canonical);
    // The trap: U+06D5 U+0654 recomposes to the ISIRI-forbidden U+06C0 under
    // NFC, so the output must survive a further NFC pass unchanged.
    expect(canonical.normalize("NFC")).toBe(canonical);
  });

  it("keeps U+0654 while stripping the harakat around it", () => {
    expect(normalize("هَّٔ")).toBe("هٔ");
  });

  it("preserves meaning-bearing ZWNJ but removes inert ones", () => {
    expect(normalize(`تن${ZWNJ}ها`)).toBe(`تن${ZWNJ}ها`);
    expect(normalize(`تن${ZWNJ}${ZWNJ}ها`)).toBe(`تن${ZWNJ}ها`);
    expect(normalize(`${ZWNJ}سلام${ZWNJ}`)).toBe("سلام");
    expect(normalize(`سلام${ZWNJ} خوب`)).toBe("سلام خوب");
  });

  it("collides تنها and تن‌ها only in the match fold, never in display", () => {
    expect(normalize(`تن${ZWNJ}ها`)).not.toBe(normalize("تنها"));
    expect(foldForMatch(`تن${ZWNJ}ها`)).toBe(foldForMatch("تنها"));
  });

  it("folds Arabic-Indic digits to Persian and leaves ASCII alone", () => {
    expect(normalize("١٢٣")).toBe("۱۲۳");
    expect(normalize("123")).toBe("123");
    expect(normalize("١٢٣", { digits: "latin" })).toBe("123");
    expect(normalize("۱۲۳", { digits: "latin" })).toBe("123");
  });

  it("folds Arabic presentation forms via NFKC", () => {
    expect(normalize("ﻢﻣ")).toBe("مم");
    expect(normalize("ﻻ")).toBe("لا");
  });

  it("localizes punctuation only when asked", () => {
    expect(normalize("chetori?")).toBe("chetori?");
    expect(normalize("chetori?", { punctuation: true })).toBe("chetori؟");
  });

  it("handles empty and whitespace-only input", () => {
    expect(normalize("")).toBe("");
    expect(normalize("   ")).toBe("   ");
  });
});
